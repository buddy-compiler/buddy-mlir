"""Check a pipeline stage's public MLIR ABI and emit its C++ binding constants."""

import argparse
import json
import re
from pathlib import Path


def check_signature(directory, phase, inputs, outputs):
    name = f"forward_{phase}"
    source = (directory / f"{name}-f16.mlir").read_text()
    matches = re.findall(
        rf"^\s*func\.func @{name}\(([^\n]*)\) -> \(([^\n]*)\)",
        source,
        re.MULTILINE,
    )
    if len(matches) != 1:
        raise ValueError(f"{name} must have exactly one public entry point")
    args, results = matches[0]
    actual = [
        re.findall(r"memref<([^>]+)>", field) for field in (args, results)
    ]
    if actual != [inputs, outputs]:
        raise ValueError(f"{name} ABI differs from stage config: {actual}")
    print(
        f"{name}: {len(inputs)} inputs, {len(outputs)} results; "
        f"data {inputs[1]} -> {outputs[-1]}"
    )


def verify_stage(config, directory, header):
    stage = config["pipeline_stage"]
    start = stage["start_layer"]
    end = stage["end_layer"]
    total = stage["total_layers"]
    count = end - start
    shape = config["shape"]
    width = stage["activation_width"]
    vocab = shape["vocab_size"]
    context = shape["max_token_len"]
    heads = shape["head_num"]
    head_dim = shape["hidden_size"]
    (weights,) = config["weights"]
    elements = weights["num_elements"]
    if (
        not 0 <= start < end <= total
        or stage["activation_type"] != "f16"
        or weights["element_type"] != "f16"
        or shape["num_hidden_layers"] != count
        or shape["kv_layers"] != 2 * count
    ):
        raise ValueError(
            "expected FP16 stage config with two KV tensors per layer"
        )

    param = f"{elements}xf16"
    kv = f"1x{heads}x{context}x{head_dim}xf16"
    pos = "1xi64"
    for phase, rows in (("prefill", context), ("decode", 1)):
        data = f"1x{rows}x{width}xf16" if start else f"1x{rows}xi64"
        output = f"1x{rows}x{vocab if end == total else width}xf16"
        cache = (
            [kv, kv] * count if phase == "prefill" else [pos, kv, kv] * count
        )
        inputs = [param, data] + (cache if phase == "decode" else [])
        check_signature(directory, phase, inputs, cache + [output])

    path = directory / weights["file"]
    if path.stat().st_size != elements * 2:
        raise ValueError(
            f"{path}: weight file length differs from the stage config"
        )
    print(
        f"layer range [{start}, {end}); {count * 2} KV tensors; {elements} FP16 weights"
    )

    if header:
        fields = [
            start,
            end,
            total,
            context,
            width,
            vocab,
            config["tokens"]["eos_id"],
        ]
        signature = ", ".join(["PositionRef *, KVRef *, KVRef *"] * count)
        header.write_text(
            "// Generated by verify_pipeline_stage.py.\n"
            "constexpr StageConfig config{"
            + ", ".join(map(str, fields))
            + ", ActivationType::F16};\n"
            f"constexpr size_t weightElements = {elements};\n"
            f"constexpr size_t kvHeads = {heads};\n"
            f"constexpr size_t headDim = {head_dim};\n"
            f"constexpr char weightFile[] = {json.dumps(weights['file'])};\n"
            "#define BUDDY_STAGE_DECODE_ARGS " + signature + "\n"
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--stage-dir", type=Path, required=True)
    parser.add_argument("--header", type=Path)
    args = parser.parse_args()
    config = json.loads((args.stage_dir / "config.json").read_text())
    verify_stage(config, args.stage_dir, args.header)


if __name__ == "__main__":
    main()
